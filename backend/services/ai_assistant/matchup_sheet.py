"""Matchup sheet schema, hand-written seed rows, and a read-only DB builder.

What this module actually does
------------------------------
1. Declares two documentation-only schemas, ``ARCHETYPE_PROFILE_SCHEMA`` and
   ``MATCHUP_SHEET_SCHEMA``. They are plain dicts describing the intended shape;
   nothing in this module generates them.
2. Ships three hand-written seed sheets (``SEED_SHEETS``) for ONE archetype key
   (``greninja`` / ``mega_greninja``). They are user notes typed 2026-09-07 and
   stay ``verified: false``; they were never checked against card text. They are
   only returned when the caller asks for that exact archetype, and every
   returned seed row carries a ``placeholder_note``.
3. Can derive a read-only matchup sheet from rows already stored in the
   ``format_archetype_briefs`` table (the ``profile`` JSONB written by
   ``services.limitless_decks.meta_field``). This path only *reads*: no DDL, no
   inserts, no network calls. Derived breakpoints compare stored printed attack
   damage against stored HP and ignore weakness / resistance / tools /
   abilities / cross-card combos, so they are always ``verified: false``.

What this module does NOT do
----------------------------
* There is no "nightly archetype profile" job. Nothing in this repository
  generates archetype profiles on a schedule; earlier revisions of this file
  claimed one. ``ARCHETYPE_PROFILE_SCHEMA`` is documentation only.
* It never invents cross-card kill lines and never substitutes another
  archetype's data. A missing or unknown ``user_archetype`` yields an explicit
  ``{"available": False, "reason": ..., "matchups": []}`` result instead of
  silently defaulting to an unrelated archetype.

``docs/MATCHUP_SHEET.md`` still describes the intended two-layer design and its
"每晚 batch" wording; treat that as aspirational, not implemented.

Public functions:
    get_matchup_sheet(user_archetype, opponent_archetype) -> dict
    list_matchup_sheets() -> list[dict]
"""

