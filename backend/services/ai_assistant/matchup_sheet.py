def _norm(value: Any) -> str:
    return str(value or "").strip().lower().replace(" ", "").replace("／", "/")


def _canonical_archetype(value: Any) -> str:
    key = _norm(value)
    if not key:
        return ""
    return ARCHETYPE_ALIASES.get(key, key)


def _json_obj(value: Any) -> dict[str, Any]:
    """psycopg2 normally returns jsonb as dict; tolerate a raw JSON string too."""
    if isinstance(value, dict):
        return value
    if isinstance(value, str) and value.strip():
        try:
            import json

            parsed = json.loads(value)
            return parsed if isinstance(parsed, dict) else {}
        except Exception:
            return {}
    return {}


def _seed_placeholder_sheets(user_id: str, opp_id: str, opp_raw: str) -> list[dict[str, Any]]:
    """Return seeds ONLY for the one seeded archetype, clearly labelled."""
    rows: list[dict[str, Any]] = []
    for row in SEED_SHEETS:
        if _canonical_archetype(row.get("user_archetype")) != user_id:
            continue
        if opp_raw:
            if not opp_id or _canonical_archetype(row.get("opponent_archetype")) != opp_id:
                continue
        sheet = dict(row)
        sheet["verified"] = False
        sheet["placeholder"] = True
        sheet["placeholder_note"] = PLACEHOLDER_NOTE
        rows.append(sheet)
    return rows


def _load_briefs() -> tuple[list[dict[str, Any]], str | None]:
    """Read-only fetch of stored archetype briefs. Never creates or writes tables."""
    try:
        import database  # backend.database
    except Exception as exc:  # pragma: no cover - import environment dependent
        return [], f"database module unavailable: {exc}"

    conn = None
    try:
        conn = database.get_db_connection()
        if not conn:
            return [], "database unavailable"
        cursor = conn.cursor()
        cursor.execute(
            """
            SELECT combo_key, label, label_zh, last_seen_month, last_rank,
                   last_share, last_n, sample_deck_ids, profile, analysis
            FROM format_archetype_briefs
            ORDER BY last_seen_month DESC NULLS LAST, last_rank NULLS LAST
            """
        )
        return [dict(row) for row in cursor.fetchall() or []], None
    except Exception as exc:
        return [], f"format_archetype_briefs unavailable: {exc}"
    finally:
        if conn is not None:
            try:
                conn.rollback()
            except Exception:
                pass
            try:
                conn.close()
            except Exception:
                pass


def _brief_matches(brief: dict[str, Any], query: str) -> bool:
    if not query:
        return False
    combo_key = _norm(brief.get("combo_key"))
    if query == combo_key:
        return True
    if query in {part for part in combo_key.split("+") if part}:
        return True
    if query in _norm(brief.get("label")) or query in _norm(brief.get("label_zh")):
        return True
    profile = _json_obj(brief.get("profile"))
    for family in profile.get("families") or []:
        if isinstance(family, dict) and query == _norm(family.get("id")):
            return True
    return False


def _find_brief(briefs: list[dict[str, Any]], raw: str) -> dict[str, Any] | None:
    query = _norm(raw)
    if not query:
        return None
    for brief in briefs:
        if _brief_matches(brief, query):
            return brief
    return None


def _profile_facts(brief: dict[str, Any]) -> dict[str, Any]:
    profile = _json_obj(brief.get("profile"))
    sample_ids = brief.get("sample_deck_ids")
    if isinstance(sample_ids, str):
        try:
            import json

            sample_ids = json.loads(sample_ids)
        except Exception:
            sample_ids = []
    return {
        "combo_key": brief.get("combo_key"),
        "label": brief.get("label"),
        "label_zh": brief.get("label_zh"),
        "last_seen_month": brief.get("last_seen_month"),
        "sample_deck_count": len(sample_ids or []) if isinstance(sample_ids, list) else 0,
        "families": profile.get("families") or [],
        "hp_table": profile.get("hp_table") or [],
        "pokemon_kits": profile.get("pokemon_kits") or [],
        "skill_catalog": profile.get("skill_catalog") or [],
    }


def _collect_attacks(profile: dict[str, Any]) -> list[dict[str, Any]]:
    """Flatten stored printed attacks; mark which ones are safe fixed-damage."""
    attacks: list[dict[str, Any]] = []
    seen = set()
    for kit in profile.get("pokemon_kits") or []:
        if not isinstance(kit, dict):
            continue
        attacker = kit.get("name") or kit.get("card_id") or "?"
        for attack in kit.get("attacks") or []:
            if not isinstance(attack, dict):
                continue
            raw = str(attack.get("damage") or "").strip()
            value = attack.get("damage_value")
            try:
                value = int(value)
            except (TypeError, ValueError):
                value = None
            effect = str(attack.get("effect") or "").strip()
            fixed = bool(value) and not _VARIABLE_DAMAGE_RE.search(raw) and not effect
            key = (attacker, attack.get("name"), raw)
            if key in seen:
                continue
            seen.add(key)
            attacks.append(
                {
                    "attacker": attacker,
                    "name": attack.get("name") or "",
                    "damage": raw,
                    "damage_value": value,
                    "fixed": fixed,
                    "effect": effect,
                }
            )
    return attacks


def _printed_breakpoints(user_profile: dict[str, Any], opp_profile: dict[str, Any]) -> list[dict[str, Any]]:
    """Strictly mechanical printed-damage vs stored-HP comparison.

    ``killed_by`` is only filled for attacks with fixed printed damage and no
    effect text, so ``damage >= hp`` is a sound lower-bound claim.
    ``not_killed_by`` is only filled when EVERY parsed attack is fixed damage.
    """
    attacks = _collect_attacks(user_profile)
    all_fixed = bool(attacks) and all(a["fixed"] for a in attacks)
    defenders = [
        row
        for row in (opp_profile.get("hp_table") or [])
        if isinstance(row, dict) and isinstance(row.get("hp"), int) and row["hp"] > 0
    ]
    breakpoints: list[dict[str, Any]] = []
    for defender in defenders:
        hp = int(defender["hp"])
        killed = [a for a in attacks if a["fixed"] and a["damage_value"] >= hp]
        breakpoints.append(
            {
                "defender": defender.get("name") or defender.get("card_id") or "?",
                "hp": hp,
                "modifier": "none",
                "modifier_note": "純印刷招式傷害對存庫 HP；未計弱點／抗性／道具／特性／跨卡特攻",
                "effective_hp": hp,
                "killed_by": [
                    f"{a['attacker']}｜{a['name']} {a['damage']}".strip() for a in killed
                ],
                "not_killed_by": (
                    [
                        f"{a['attacker']}｜{a['name']} {a['damage']}".strip()
                        for a in attacks
                        if a["fixed"] and a["damage_value"] < hp
                    ]
                    if all_fixed
                    else []
                ),
                "method": "printed_damage_vs_hp",
                "verified": False,
            }
        )
    return breakpoints


def _derive_sheet(user_brief: dict[str, Any], opp_brief: dict[str, Any] | None) -> dict[str, Any]:
    user_profile = _json_obj(user_brief.get("profile"))
    opp_profile = _json_obj(opp_brief.get("profile")) if opp_brief else {}
    breakpoints = _printed_breakpoints(user_profile, opp_profile) if opp_brief else []
    limitations = [
        "由 format_archetype_briefs 存庫 profile 即場讀取，未對過卡文，verified=false。",
        "breakpoints 只比較印刷招式傷害同存庫 HP，未計弱點／抗性／道具／特性／點傷／跨卡組合。",
        "setup／quirks／advantages／kill_lines 屬判斷內容，本 builder 唔會生成。",
    ]
    if opp_brief is None:
        limitations.append("未提供或未收錄對手 archetype，只回用戶套 profile 事實。")
    return {
        "schema_version": SCHEMA_VERSION,
        "user_archetype": user_brief.get("combo_key"),
        "user_display_name": user_brief.get("label_zh") or user_brief.get("label"),
        "opponent_archetype": (opp_brief or {}).get("combo_key"),
        "opponent_display_name": (opp_brief or {}).get("label_zh") or (opp_brief or {}).get("label"),
        "verified": False,
        "placeholder": False,
        "derived": True,
        "source": "db:format_archetype_briefs",
        "setup": {},
        "quirks": [],
        "breakpoints": breakpoints,
        "vs_archetype": {
            "advantages": [],
            "disadvantages": [],
            "kill_lines": [],
            "tempo_note": None,
        },
        "profile_facts": {
            "user": _profile_facts(user_brief),
            "opponent": _profile_facts(opp_brief) if opp_brief else None,
        },
        "limitations": limitations,
    }


def get_matchup_sheet(user_archetype: str = "", opponent_archetype: str = "") -> dict[str, Any]:
    """Build a matchup sheet for a CONCRETE archetype key, or report no data.

    ``user_archetype`` is required. There is no default archetype: a blank or
    unknown key returns ``available=False`` with a reason instead of returning
    another archetype's sheet. Hand-written seeds are returned only when the
    requested key is exactly the one seeded archetype (greninja). Otherwise a
    read-only derivation from ``format_archetype_briefs`` is attempted.
    """
    user_raw = str(user_archetype or "").strip()
    opp_raw = str(opponent_archetype or "").strip()
    user_id = _canonical_archetype(user_raw)
    opp_id = _canonical_archetype(opp_raw)

    result: dict[str, Any] = {
        "schema_version": SCHEMA_VERSION,
        "schema": MATCHUP_SHEET_SCHEMA,
        "profile_schema": ARCHETYPE_PROFILE_SCHEMA,
        "generation": dict(GENERATION_NOTES),
        "user_archetype_key": user_id,
        "opponent_archetype_key": opp_id,
        "available": False,
        "reason": "",
        "count": 0,
        "matchups": [],
        "sheets": [],  # backward-compatible alias of `matchups`
        "available_sheets": list_matchup_sheets(),
        "note": "",
    }

    if not user_raw or not user_id:
        result["reason"] = "missing_user_archetype"
        result["note"] = (
            "get_matchup_sheet 需要具體 user_archetype；"
            "唔會再默認代入 mega_greninja 或者其他套牌。"
        )
        return result

    # Real stored profile data wins; hand-written seeds are only a last resort.
    briefs, db_reason = _load_briefs()
    user_brief = _find_brief(briefs, user_raw) if not db_reason else None
    if user_brief:
        opp_brief = _find_brief(briefs, opp_raw) if opp_raw else None
        sheets = [_derive_sheet(user_brief, opp_brief)]
        result["available"] = True
        result["reason"] = "derived_from_db_profile"
        result["count"] = len(sheets)
        result["matchups"] = sheets
        result["sheets"] = sheets
        result["note"] = (
            "由 format_archetype_briefs 存庫 profile 唯讀推導；verified=false，"
            "breakpoints 只計印刷傷害對 HP。"
        )
        if opp_raw and not opp_brief:
            result["note"] += f" 對手 '{opp_raw}' 未收錄，未提供對局斷點。"
        return result

    seeded = _seed_placeholder_sheets(user_id, opp_id, opp_raw)
    if seeded:
        result["available"] = True
        result["reason"] = "seed_placeholder"
        result["count"] = len(seeded)
        result["matchups"] = seeded
        result["sheets"] = seeded
        result["note"] = (
            "只有 greninja／mega_greninja 嘅手寫種子；全部 verified=false，"
            "係 placeholder，唔係卡庫或 profile job 產生。"
        )
        return result

    if db_reason:
        result["reason"] = "no_profile_data"
        result["note"] = f"無真實 archetype profile 可用：{db_reason}"
        return result

    result["reason"] = "no_profile_data_for_archetype"
    result["note"] = (
        f"format_archetype_briefs 無 user_archetype='{user_raw}' 嘅 profile；"
        "唔會用其他套牌數據代替。"
    )
    return result
